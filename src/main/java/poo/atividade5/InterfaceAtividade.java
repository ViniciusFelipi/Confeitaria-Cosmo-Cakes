    private void btnGravarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGravarActionPerformed
        // TODO add your handling code here:
        String sql = "INSERT INTO tb_bolos(nome_bolo, preco_kg, ingredientes, descricao) VALUES(?,?,?,?)";

        try (Connection con = Conexao.conectar(); java.sql.PreparedStatement pst = con.prepareStatement(sql)) {

            pst.setString(1, txtNome.getText());
            pst.setDouble(2, Double.parseDouble(txtPreco.getText().replace(",", ".")));
            pst.setString(3, txtIngredientes.getText());
            pst.setString(4, txtDescricao.getText());

            pst.executeUpdate();
            javax.swing.JOptionPane.showMessageDialog(null, "Bolo cadastrado com sucesso!");
            limparCampos();

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, "Erro ao gravar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnGravarActionPerformed

    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        // TODO add your handling code here:
        String sql = "UPDATE tb_bolos SET nome_bolo=?, preco_kg=?, ingredientes=?, descricao=? WHERE id_bolo=?";

        try (Connection con = Conexao.conectar(); java.sql.PreparedStatement pst = con.prepareStatement(sql)) {

            pst.setString(1, txtNome.getText());
            pst.setDouble(2, Double.parseDouble(txtPreco.getText().replace(",", ".")));
            pst.setString(3, txtIngredientes.getText());
            pst.setString(4, txtDescricao.getText()); // Pega todo o texto da área
            pst.setInt(5, Integer.parseInt(txtCodigo.getText()));

            int adicionado = pst.executeUpdate();

            if (adicionado > 0) {
                javax.swing.JOptionPane.showMessageDialog(null, "Dados do bolo alterados com sucesso!");
                limparCampos();
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, "Erro ao alterar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnAlterarActionPerformed

    private void btnLocalizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLocalizarActionPerformed
        // TODO add your handling code here:
        String sql = "SELECT * FROM tb_bolos WHERE id_bolo = ?";

        try (Connection con = Conexao.conectar(); java.sql.PreparedStatement pst = con.prepareStatement(sql)) {

            pst.setInt(1, Integer.parseInt(txtCodigo.getText()));
            java.sql.ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                txtNome.setText(rs.getString("nome_bolo"));
                txtPreco.setText(rs.getString("preco_kg"));
                txtIngredientes.setText(rs.getString("ingredientes"));
                txtDescricao.setText(rs.getString("descricao"));
                ativarCamposLocalizar(true);
            } else {
                javax.swing.JOptionPane.showMessageDialog(null, "Bolo não encontrado!");
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, "Erro na busca: " + e.getMessage());
        }
    }//GEN-LAST:event_btnLocalizarActionPerformed

