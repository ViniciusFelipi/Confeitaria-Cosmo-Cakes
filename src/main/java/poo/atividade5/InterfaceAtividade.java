    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        // TODO add your handling code here:
        int confirma = javax.swing.JOptionPane.showConfirmDialog(null, "Tem certeza que deseja excluir este bolo?", "Atenção", javax.swing.JOptionPane.YES_NO_OPTION);

        if (confirma == javax.swing.JOptionPane.YES_OPTION) {
            String sql = "DELETE FROM tb_bolos WHERE id_bolo=?";
            try (Connection con = Conexao.conectar(); java.sql.PreparedStatement pst = con.prepareStatement(sql)) {

                pst.setInt(1, Integer.parseInt(txtCodigo.getText()));
                pst.executeUpdate();

                javax.swing.JOptionPane.showMessageDialog(null, "Bolo removido com sucesso!");
                limparCampos();
            } catch (Exception e) {
                javax.swing.JOptionPane.showMessageDialog(null, "Erro ao excluir: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

